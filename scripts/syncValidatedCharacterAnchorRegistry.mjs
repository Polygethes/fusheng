import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const anchorsRoot = path.join(projectRoot, ".codex", "anchors");
const outputPath = path.join(projectRoot, "src", "data", "validatedCharacterAnchorRegistry.js");

async function directoriesAt(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  return entries.filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort();
}

function posixRelative(absolutePath) {
  return path.relative(projectRoot, absolutePath).split(path.sep).join("/");
}

const entries = {};
for (const sceneId of await directoriesAt(anchorsRoot)) {
  const characterRoot = path.join(anchorsRoot, sceneId, "characters");
  let characterIds = [];
  try {
    characterIds = await directoriesAt(characterRoot);
  } catch (error) {
    if (error?.code === "ENOENT") continue;
    throw error;
  }
  for (const characterId of characterIds) {
    const directory = path.join(characterRoot, characterId);
    const anchorPath = path.join(directory, "anchor-payload.json");
    const manifestPath = path.join(directory, "manifest.json");
    const memoryPath = path.join(directory, "memory-seed.json");
    let manifestText = "";
    try {
      manifestText = await readFile(manifestPath, "utf8");
    } catch (error) {
      if (error?.code === "ENOENT") continue;
      throw error;
    }
    const manifest = JSON.parse(manifestText);
    if (manifest.gates?.holdouts !== "passed" || manifest.gates?.runtimeMapping !== "mapped") continue;

    const foundationPath = path.join(
      directory,
      manifest.artifacts?.characterFoundation || "character-foundation.json",
    );
    let foundationText = "";
    let memoryText = "";
    let sourcePath = foundationPath;
    let sourceAuthority = "character-foundation";
    let usesSeparatedFoundation = true;
    try {
      [foundationText, memoryText] = await Promise.all([
        readFile(foundationPath, "utf8"),
        readFile(memoryPath, "utf8"),
      ]);
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
      usesSeparatedFoundation = false;
      sourcePath = anchorPath;
      sourceAuthority = "author-anchor-legacy-migration";
      try {
        [foundationText, memoryText] = await Promise.all([
          readFile(anchorPath, "utf8"),
          readFile(memoryPath, "utf8"),
        ]);
      } catch (fallbackError) {
        if (fallbackError?.code === "ENOENT") continue;
        throw fallbackError;
      }
    }
    const foundation = JSON.parse(foundationText);
    const memorySeed = JSON.parse(memoryText);
    if (foundation.status !== "validated") continue;
    if (foundation.characterId !== characterId) {
      throw new TypeError(`foundation characterId mismatch: ${posixRelative(sourcePath)}`);
    }
    if (memorySeed.ownerCharacterId !== characterId) {
      throw new TypeError(`memory ownerCharacterId mismatch: ${posixRelative(memoryPath)}`);
    }
    const bindingSceneIds = (foundation.sceneBindings || []).map((row) => row?.sceneId).filter(Boolean);
    if (bindingSceneIds.length && !bindingSceneIds.includes(sceneId)) {
      throw new TypeError(`anchor scene binding mismatch: ${posixRelative(anchorPath)}`);
    }
    const key = `${sceneId}::${characterId}`;
    entries[key] = {
      sceneId,
      characterId,
      source: {
        path: posixRelative(sourcePath),
        sha256: createHash("sha256").update(foundationText).digest("hex"),
        authority: sourceAuthority,
        generatedProjection: usesSeparatedFoundation,
        memoryPath: posixRelative(memoryPath),
        memorySha256: createHash("sha256").update(memoryText).digest("hex"),
      },
      ...(usesSeparatedFoundation ? { characterFoundation: foundation } : { anchor: foundation }),
      memorySeed,
    };
  }
}

const generated = `// Generated by scripts/syncValidatedCharacterAnchorRegistry.mjs.\n`
  + `// Do not hand-edit. Change the source anchor and run the sync script.\n\n`
  + `function deepFreeze(value) {\n`
  + `  if (!value || typeof value !== "object" || Object.isFrozen(value)) return value;\n`
  + `  for (const child of Object.values(value)) deepFreeze(child);\n`
  + `  return Object.freeze(value);\n`
  + `}\n\n`
  + `export const VALIDATED_CHARACTER_ANCHOR_REGISTRY_VERSION = 1;\n\n`
  + `export const VALIDATED_CHARACTER_ANCHOR_REGISTRY = deepFreeze(${JSON.stringify({
    schemaVersion: 1,
    sourceRoot: ".codex/anchors",
    entries,
  }, null, 2)});\n`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated, "utf8");
console.log("validated character anchor registry synced", {
  output: posixRelative(outputPath),
  entries: Object.keys(entries),
});
