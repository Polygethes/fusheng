import assert from "node:assert/strict";

const skills = await import("../src/worldbuilding/skills.js");

assert.equal(typeof skills.buildPlayableWorldFromSetup, "function", "worldbuilding skill module should build a playable world from setup prompts");

const result = skills.buildPlayableWorldFromSetup({
  setupWorldPrompt: "《西游记》：一条漫长的取经路，神佛、妖怪、官府、山野和人心试炼同时存在，每一站都有自己的规矩。",
  setupPeoplePrompt: "一个必须抵达的人、几个本性不同的同行者、沿途的妖怪、求助的人、阻拦的人和旁观的神佛。",
});

assert.ok(result.usedSkills?.includes("世界建立 Skill"), "world creation should explicitly use the world-building skill");
assert.ok(result.usedSkills?.includes("戏剧人物 Skill"), "world creation should explicitly use the dramatic-character skill");
assert.ok(result.project.title.includes("西游") || result.town.name.includes("取经"), "created world should be named from the user's chosen world");
assert.ok(result.worldSetup.generatedBySkills, "created world should record that it was generated by skills");
assert.ok(result.worldSetup.skillContract?.requiredFields?.includes("baseRules"), "created world should carry the world skill contract");
assert.ok(result.characters.length >= 4, "created world should contain a playable cast");
assert.ok(result.locations.length >= 3, "created world should contain playable locations");
assert.ok(result.relationships.length >= result.characters.length - 1, "created world should include relationship pressure");
assert.ok(result.ui.activeCharacterIds.length >= 2, "created world should activate an initial cast");
assert.ok(result.ui.selectedLocationId === result.locations[0].id, "created world should select an initial location");

const serialized = JSON.stringify(result);
for (const forbidden of ["格里高尔", "萨姆沙公寓", "公司书记员"]) {
  assert.ok(!serialized.includes(forbidden), `created world should not leak the old Metamorphosis seed: ${forbidden}`);
}

for (const character of result.characters) {
  const audit = skills.auditDramaticCharacter(character, result.characters);
  assert.ok(audit.score >= 80, `${character.name} should satisfy dramatic-character skill, got ${audit.score}`);
}

console.log("setupSkillWorldCreation:test passed", {
  title: result.project.title,
  characters: result.characters.length,
  locations: result.locations.length,
});
