import assert from "node:assert/strict";
import { initialState } from "../src/data/seed.js";
import { playNext } from "../src/engine/mockEngine.js";
import { buildObservationEvents, inferPixelPreview, renderApp } from "../src/ui/render.js";
import { randomEventOptionsForState } from "../src/worldbuilding/injectedEvents.js";
import { auditDramaticCharacter, buildPlayableWorldFromSetup } from "../src/worldbuilding/skills.js";

const state = buildPlayableWorldFromSetup({
  setupWorldPrompt: "仙侠世界当中，正邪两派各种物种所汇集的一个中立城市。",
  setupPeoplePrompt: "正道修士、邪派使者、妖族、鬼修、龙裔、器灵、散修和城中执法者都被中立城规矩暂时压住。",
});

const setupHtml = renderApp(initialState);
assert.ok(setupHtml.includes("仙侠中立城"), "setup presets should offer the xianxia neutral city prototype");

const preview = inferPixelPreview({
  setupWorldPrompt: "仙侠世界当中，正邪两派各种物种所汇集的一个中立城市。",
  setupPeoplePrompt: "正道修士、邪派使者、妖族、鬼修、龙裔、器灵。",
});
assert.equal(preview.theme, "xianxia-neutral-city", "pixel preview should infer xianxia neutral city");
assert.ok(preview.objects.includes("灵契") && preview.locations.includes("四方法契门"), "xianxia preview should show world-specific objects and districts");

assert.ok(state.usedSkills.includes("世界建立 Skill"), "xianxia city must be generated by world-building skill");
assert.ok(state.usedSkills.includes("戏剧人物 Skill"), "xianxia city must be generated by dramatic-character skill");
assert.match(`${state.project.title} ${state.town.name} ${state.town.summary}`, /仙侠|中立|城/, "generated world should be an xianxia neutral city");
assert.ok(state.worldSetup.generatedBySkills, "generated state should record skill generation");

const randomEvents = randomEventOptionsForState(state).join("\n");
assert.ok(/灵契|妖丹|庇护|破禁|渡令/.test(randomEvents), "random event pool should follow the xianxia city");
assert.ok(!/格里高尔|公司书记员|家庭账本/.test(randomEvents), "random event pool should not leak Metamorphosis events into xianxia city");

const serialized = JSON.stringify(state);
for (const forbidden of ["格里高尔", "萨姆沙", "布拉格", "家庭餐桌", "公司柜台", "取经", "唐僧"]) {
  assert.ok(!serialized.includes(forbidden), `xianxia world should not leak old presets: ${forbidden}`);
}

assert.ok(state.characters.length >= 6, "neutral city needs a multi-faction cast");
assert.ok(state.locations.length >= 5, "neutral city needs several city districts that can run in parallel");
assert.ok(state.relationships.length >= state.characters.length, "neutral city needs cross-faction relationship pressure");

const castText = state.characters.map((character) => `${character.name} ${character.publicIdentity}`).join("\n");
for (const term of ["正道", "邪", "妖", "鬼", "龙", "器灵"]) {
  assert.ok(castText.includes(term), `cast should include faction/species distinction: ${term}`);
}

const rules = [...state.town.publicRules, ...state.town.hiddenRules, state.town.pressureClock].join("\n");
for (const term of ["中立", "不可杀", "庇护", "灵契", "破禁"]) {
  assert.ok(rules.includes(term), `world rules should create event pressure around ${term}`);
}

const eventText = state.locations.flatMap((location) => location.likelyEvents || []).join("\n");
for (const term of ["扣押", "破禁", "审讯", "拍卖", "追捕", "庇护"]) {
  assert.ok(eventText.includes(term), `locations should contain event triggers, not texture only: ${term}`);
}

const visibleLines = new Set(state.characters.map((character) => character.actionLines.visible));
assert.equal(visibleLines.size, state.characters.length, "characters should not share the same visible action line");

for (const character of state.characters) {
  const audit = auditDramaticCharacter(character, state.characters);
  assert.ok(audit.score >= 80, `${character.name} should satisfy dramatic-character skill, got ${audit.score}`);
}

state.ui.timeGrain = "day";
state.ui.focusMode = "ambient";
state.ui.activeTab = "observe";
const draft = playNext(state);
const events = buildObservationEvents(draft, state);
const feedText = events.flatMap((event) => [event.text, ...(event.beats || []).map((beat) => beat.text)]).join("\n");

assert.ok(draft.periodSimulation?.ticks?.length >= 5, "one play should run the city across a full day");
assert.ok(/扣押|破禁|审讯|拍卖|追捕|庇护|灵契|妖丹|剑匣|界石/.test(feedText), "observation feed should show city events, not harmless detail");
assert.ok(!/这对大家都好|我只是照规矩办|现在不是说这个的时候/.test(feedText), "xianxia characters should not speak generic fallback defenses");
assert.ok(!/先停下，.+把声音压低/.test(feedText), "xianxia location events should not collapse into generic pauses");
assert.ok(!/桌边一点响动|刚才的话还悬在房间里|脚步停在门槛外/.test(feedText), "xianxia distant aftermath should not use generic room/table residue");
assert.ok(!/一件小事|无关紧要|低精度|后台运行|私人模拟/.test(feedText), "observation feed should not expose placeholder or engine language");

console.log("xianxiaNeutralCityWorld:test passed", {
  title: state.project.title,
  cast: state.characters.map((character) => character.name),
  locations: state.locations.map((location) => location.name),
  sample: events[0]?.text,
});
