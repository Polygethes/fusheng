import assert from "node:assert/strict";
import { buildPlayableWorldFromSetup } from "../src/worldbuilding/skills.js";
import { createTavernWorldRuntimeV27, projectTavernSituationV27 } from "../src/server/pipeline/tavernWorldRuntimeV27.mjs";
const MOTHER = "char_xyy_xiemu", ZHOU = "char_xyy_zhoumin";
const PARCEL = "tavern_delivery_medicine_parcel", MANIFEST = "tavern_delivery_manifest";
const seed = buildPlayableWorldFromSetup({ setupWorldPrompt: "来源于《逍遥游》，从第一集《璞玉》开场前开始。", setupPeoplePrompt: "谢真石、周珉、洛照、严执中、谢恒、谢母、陈砚。" });
const instance = createTavernWorldRuntimeV27(seed, { pacingMode: "scene", positions: { [MOTHER]: "hall" } });
let seq = 0;
const submit = (actorId, primitive, payload) => instance.coordinator.submitActionAttempt({ actorId, primitive, payload, attemptId: `delivery-contract:${++seq}` });
const state = () => instance.coordinator.worldState;
const binding = objectId => {
  const projection = projectTavernSituationV27({ worldState: state(), characterId: MOTHER });
  const affordance = projection.availableAffordances.find(row => row.operation === "accept_delivery" && row.objectId === objectId);
  return affordance ? projection.recipientPrivateBindings.affordanceBindingByHandle[affordance.id] : null;
};
assert.equal(binding(PARCEL), null, "a recipient cannot acknowledge custody while another person still holds the parcel");
await submit(ZHOU, "handle", { objectId: PARCEL, operation: "place" });
assert.ok(binding(PARCEL), "the actual recipient needs an executable acceptance operation");
const acceptedBinding = binding(PARCEL);
const wrongRecipient = await submit(ZHOU, "use_affordance", { capabilityBinding: acceptedBinding });
assert.equal(wrongRecipient.status, "failed");
const accepted = await submit(MOTHER, "use_affordance", { capabilityBinding: acceptedBinding, visibleAction: "AUDIT_ONLY_清单和药一起全收了" });
assert.equal(accepted.status, "success");
assert.equal(state().objects[PARCEL].state.acceptedByCharacterId, MOTHER);
assert.equal(state().objects[MANIFEST].state.accepted, false);
assert.equal(binding(MANIFEST), null);
assert.ok(!JSON.stringify(accepted).includes("AUDIT_ONLY"));
await submit(ZHOU, "handle", { objectId: MANIFEST, operation: "place" });
assert.equal((await submit(MOTHER, "use_affordance", { capabilityBinding: binding(MANIFEST) })).status, "success");
assert.equal(state().objects[MANIFEST].state.accepted, true);
assert.equal((await submit(MOTHER, "use_affordance", { capabilityBinding: acceptedBinding })).status, "failed", "acceptance cannot be counted twice");
for (const actor of instance.runtime.actors.values()) await actor.close();
console.log("Delivery acceptance: real recipient, actual custody, independent items, no prose effects or duplicate acceptance passed.");
