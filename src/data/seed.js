// Deterministic id factory: ids only need uniqueness, not unpredictability.
// A per-process sequence keeps every contract run reproducible (same action
// sequence, same ids, same downstream variant keys).  Long-lived entry points
// (browser app, server) set a session salt so ids stay unique across restarts
// while persisted state still references old ids.
let idSequence = 0;
let idSessionSalt = "";

export function setSessionIdSalt(salt = "") {
  idSessionSalt = String(salt).replace(/[^a-z0-9_-]/gi, "").slice(0, 8);
}

export function createId(prefix) {
  idSequence += 1;
  const core = idSequence.toString(36);
  return `${prefix}_${core}${idSessionSalt ? `_${idSessionSalt}` : ""}`;
}

